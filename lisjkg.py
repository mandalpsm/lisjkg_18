def chunk_candidates(doc):
    out = []
    for nc in doc.noun_chunks:
        toks = list(nc)
        while toks and (toks[0].pos_ in EDGE_POS or toks[0].lower_ in LEAD_DROP): toks = toks[1:]
        while toks and (toks[-1].pos_ in EDGE_POS): toks = toks[:-1]
