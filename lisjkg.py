def evidence(a, b):
    co  = 1.0 if (a["co"] & b["co"]) else 0.0
    src = len(a["src"] & b["src"]) / max(1, len(a["src"] | b["src"]))
    top = float(a["emb"] @ b["emb"])
    return 0.45*co + 0.15*src + 0.40*max(0.0, top)
