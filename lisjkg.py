def clean_text(s):
    if pd.isna(s): return ""
    s = str(s).replace("&amp,", "&")                      # broken entity seen in the data
    s = html.unescape(s)
    s = re.sub(r"<[^>]+>", " ", s)
    s = unicodedata.normalize("NFKC", s)
